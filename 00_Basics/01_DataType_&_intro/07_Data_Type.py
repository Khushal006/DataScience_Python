#Data types in Python
# integers - Python integers can grow arbitrarily large (limited mainly by available memory)

print(8)
print(1.7e308)

# decimal/float - Python floating point numbers are typically limited to about 1.7e308

print(8.55)
print(1.7e308)

# boolean - python have True, False as boolean

print(True)
print(False)

# string/text - python does not have char as c++ 

print('a')
print('KhushalMachchal')

# complex numbers - python can handle calculation in imaginary numbers j is the imaginary part 

print(5+6j)

# list - python does not have array but it have list like it slightly differ

print([1,2,3,4,5])

# tuple -  built-in, immutable sequence type used to store heterogeneous data

print((1,2,3,4,5))

# Sets -  an unordered collection of unique elements implemented as a hash table, whereas c++ have sorted set

print({1,2,3,4,5})

# Dictionary - a built-in, highly flexible data structure that stores data as key-value pairs using an underlying hash table implementation. just as unorderedmapp in c++

print({'name':'Khushal','gender':'Male','weight':85})

# Type function - a built-in, Types checked function at runtime

print(type(2.5))
print(type('KhushalMachchal'))

